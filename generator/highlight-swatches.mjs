// Renders a swatch for every health check highlight colour in highlight-swatches.json into
// assets/highlight-swatches/<HEX>.svg, with a catalogue README. READMEs use them in their
// HealthCheck tables, in place of third-party placeholder image services.
//
// The swatches follow the colour swatches in the brand guide: a 16 px square with a 3 px corner
// and a #C5D2E6 rule border, so pale highlights stay visible on a white page.
//
// Usage (from this folder): node highlight-swatches.mjs
// Only files whose bytes change are written.

import { readFile, writeFile, mkdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import { join } from "node:path";
import { config, here } from "./repos.mjs";

const { styles } = JSON.parse(await readFile(join(here, "highlight-swatches.json"), "utf8"));
const outDir = join(here, "..", "assets", "highlight-swatches");
const baseUrl = `https://raw.githubusercontent.com/${config.org}/.github/main/assets/highlight-swatches`;

export function swatchSvg(hex) {
    return [
        `<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 16 16" role="img" aria-label="#${hex}">`,
        `<rect x="0.5" y="0.5" width="15" height="15" rx="3" fill="#${hex}" stroke="#C5D2E6"/>`,
        "</svg>",
        "",
    ].join("\n");
}

async function writeIfChanged(path, text) {
    if (existsSync(path) && (await readFile(path, "utf8")) === text) return false;
    await writeFile(path, text);
    return true;
}

function catalogue() {
    const sections = Object.entries(styles).flatMap(([name, style]) => [
        `## ${name === "default" ? "Default style" : name}`,
        "",
        `From ${style.source}.${name === "default" ? " Used by every module that does not define its own highlight colours." : ""}`,
        "",
        "| Swatch | Style | Hex |",
        "|:---:|---|---|",
        ...Object.entries(style.colours).map(([label, hex]) => `| <img src="${hex}.svg" alt="#${hex}" width="16" height="16"> | ${label} | \`#${hex}\` |`),
        "",
    ]);
    return [
        "# Health check highlight swatches",
        "",
        "Colour swatches for the HealthCheck tables in AsBuiltReport module READMEs. Each one shows the background colour that a report gives a highlighted cell, so readers can match the README to the report.",
        "",
        "This folder is generated by [`generator/highlight-swatches.mjs`](../../generator/highlight-swatches.mjs) from [`highlight-swatches.json`](../../generator/highlight-swatches.json). Do not edit the files here by hand. When a module adds its own report style, add its colours to that file.",
        "",
        ...sections,
        "## Using a swatch",
        "",
        "Use the swatch for the colour the module's report uses, with the style name as the alt text:",
        "",
        "```markdown",
        `![Warning](${baseUrl}/FFF4C7.svg) VM snapshot age >= 7 days`,
        "```",
        "",
    ].join("\n");
}

await mkdir(outDir, { recursive: true });
const colours = [...new Set(Object.values(styles).flatMap((s) => Object.values(s.colours)))];
let changed = 0;
for (const hex of colours) {
    if (!/^[0-9A-F]{6}$/.test(hex)) throw new Error(`Invalid colour ${hex}: use six upper case hex digits`);
    if (await writeIfChanged(join(outDir, `${hex}.svg`), swatchSvg(hex))) changed++;
}
if (await writeIfChanged(join(outDir, "README.md"), catalogue())) changed++;
console.log(`${colours.length} swatches, ${changed} file(s) changed`);
