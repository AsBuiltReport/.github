// Renders the README section icons listed in section-icons.json into assets/section-icons/:
//   <name>.svg   32 x 32, for READMEs
//   <name>.png   96 x 96, for places that do not accept SVG
//   README.md    a catalogue of the pack, with the Markdown to use each icon
//
// The style matches the feature icons on www.asbuiltreport.com: an Octicons glyph in
// console blue on a highlighter yellow tile, corner radius 1/8 and glyph 55% of the tile.
//
// Usage (from this folder): node section-icons.mjs
// Only files whose bytes change are written.

import octicons from "@primer/octicons";
import { chromium } from "playwright";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import { join } from "node:path";
import { config, here } from "./repos.mjs";

const { icons } = JSON.parse(await readFile(join(here, "section-icons.json"), "utf8"));
const outDir = join(here, "..", "assets", "section-icons");
const baseUrl = `https://raw.githubusercontent.com/${config.org}/.github/main/assets/section-icons`;
const tile = 32;
const glyph = tile * 0.55;
const inset = (tile - glyph) / 2;

export function iconSvg(icon) {
    const source = octicons[icon.octicon];
    if (!source || !source.heights[16]) throw new Error(`Octicon ${icon.octicon}-16 not found for ${icon.name}`);
    return [
        `<svg xmlns="http://www.w3.org/2000/svg" width="${tile}" height="${tile}" viewBox="0 0 ${tile} ${tile}" role="img" aria-label="${icon.label}">`,
        `<title>${icon.label}</title>`,
        `<rect width="${tile}" height="${tile}" rx="4" fill="#FFD02B"/>`,
        `<svg x="${inset}" y="${inset}" width="${glyph}" height="${glyph}" viewBox="0 0 16 16" fill="#012456">${source.heights[16].path}</svg>`,
        "</svg>",
        "",
    ].join("\n");
}

async function writeIfChanged(path, data) {
    const buffer = Buffer.isBuffer(data) ? data : Buffer.from(data, "utf8");
    if (existsSync(path) && (await readFile(path)).equals(buffer)) return false;
    await writeFile(path, buffer);
    return true;
}

function catalogue() {
    const rows = icons.map((icon) =>
        `| <img src="${icon.name}.svg" alt="" width="32" height="32"> | \`${icon.name}\` | ${icon.headings.join(", ")} |`);
    return [
        "# README section icons",
        "",
        "Icons for the section headings of AsBuiltReport module READMEs, in place of emoji. They follow the feature icons on [www.asbuiltreport.com](https://www.asbuiltreport.com): an [Octicons](https://primer.style/octicons/) glyph in console blue `#012456` on a highlighter yellow `#FFD02B` tile.",
        "",
        "This folder is generated by [`generator/section-icons.mjs`](../../generator/section-icons.mjs) from [`section-icons.json`](../../generator/section-icons.json). Do not edit the files here by hand.",
        "",
        "| Icon | Name | Used for |",
        "|:---:|---|---|",
        ...rows,
        "",
        "## Using an icon",
        "",
        "Put the icon before the heading text. Size it to the heading: 28 for `#`, 24 for `##` and 20 for `###`. The alt text is empty because the heading already says what the section is.",
        "",
        "```markdown",
        `## <img src="${baseUrl}/getting-started.svg" alt="" width="24" height="24"> Getting Started`,
        "```",
        "",
        "Each icon is also available as a 96 x 96 PNG with the same name, for places that do not accept SVG.",
        "",
        "Octicons are by GitHub, used under the MIT License.",
        "",
    ].join("\n");
}

await mkdir(outDir, { recursive: true });
const browser = await chromium.launch();
const page = await browser.newPage({ deviceScaleFactor: 3 });
let changed = 0;
try {
    for (const icon of icons) {
        const svg = iconSvg(icon);
        if (await writeIfChanged(join(outDir, `${icon.name}.svg`), svg)) changed++;

        await page.setViewportSize({ width: tile, height: tile });
        await page.setContent(`<style>html,body{margin:0;background:transparent}</style>${svg}`);
        const png = await page.locator("body > svg").screenshot({ omitBackground: true });
        if (await writeIfChanged(join(outDir, `${icon.name}.png`), png)) changed++;
    }
} finally {
    await browser.close();
}
if (await writeIfChanged(join(outDir, "README.md"), catalogue())) changed++;
console.log(`${icons.length} icons, ${changed} file(s) changed`);
